ALTER TABLE instruments
    ADD COLUMN last_seq_no BIGINT NOT NULL DEFAULT 0;

UPDATE instruments
SET last_seq_no = (
    SELECT COALESCE(MAX(orders.seq_no), 0)
    FROM orders
    WHERE orders.symbol = instruments.symbol
);

CREATE TABLE order_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(24) NOT NULL,
    symbol VARCHAR(16) NOT NULL REFERENCES instruments(symbol),
    order_seq_no BIGINT NOT NULL,
    counterparty_seq_no BIGINT,
    user_id BIGINT,
    client_order_id UUID,
    side VARCHAR(4),
    limit_price NUMERIC(12, 4),
    quantity BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_order_events_type CHECK (
        event_type IN ('ORDER_ACCEPTED', 'ORDER_CANCELED', 'TRADE_EXECUTED')
    ),
    CONSTRAINT chk_order_events_seq_no CHECK (order_seq_no > 0),
    CONSTRAINT chk_order_events_trade_seq_no CHECK (
        counterparty_seq_no IS NULL OR counterparty_seq_no > 0
    ),
    CONSTRAINT chk_order_events_quantity CHECK (
        quantity IS NULL OR quantity > 0
    ),
    CONSTRAINT chk_order_events_accepted_payload CHECK (
        event_type <> 'ORDER_ACCEPTED'
        OR (user_id IS NOT NULL AND client_order_id IS NOT NULL
            AND side IS NOT NULL AND limit_price IS NOT NULL AND quantity IS NOT NULL)
    ),
    CONSTRAINT chk_order_events_trade_payload CHECK (
        event_type <> 'TRADE_EXECUTED'
        OR (counterparty_seq_no IS NOT NULL AND quantity IS NOT NULL)
    ),
    CONSTRAINT chk_order_events_canceled_payload CHECK (
        event_type <> 'ORDER_CANCELED'
        OR (counterparty_seq_no IS NULL AND user_id IS NULL
            AND client_order_id IS NULL AND side IS NULL
            AND limit_price IS NULL AND quantity IS NULL)
    )
);

CREATE INDEX idx_order_events_symbol_id ON order_events (symbol, id);

INSERT INTO order_events (
    event_type, symbol, order_seq_no, user_id, client_order_id, side,
    limit_price, quantity, created_at
)
SELECT 'ORDER_ACCEPTED', symbol, seq_no, user_id, client_order_id, side,
       limit_price, original_quantity, created_at
FROM orders
ORDER BY id;

INSERT INTO order_events (
    event_type, symbol, order_seq_no, counterparty_seq_no, quantity, created_at
)
SELECT 'TRADE_EXECUTED', buy_order.symbol,
       CASE WHEN buy_order.seq_no > sell_order.seq_no
            THEN buy_order.seq_no ELSE sell_order.seq_no END,
       CASE WHEN buy_order.seq_no > sell_order.seq_no
            THEN sell_order.seq_no ELSE buy_order.seq_no END,
       trades.quantity, trades.created_at
FROM trades
JOIN orders buy_order ON buy_order.id = trades.buy_order_id
JOIN orders sell_order ON sell_order.id = trades.sell_order_id
ORDER BY trades.id;

INSERT INTO order_events (event_type, symbol, order_seq_no, created_at)
SELECT 'ORDER_CANCELED', symbol, seq_no, created_at
FROM orders
WHERE status = 'CANCELED'
ORDER BY id;
